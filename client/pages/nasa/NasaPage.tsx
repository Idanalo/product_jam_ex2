import type { ApodPicture } from "@shared/schemas/nasa";
import { useState } from "react";
import { Button, Card, Spinner, useToast } from "../../components";
import { useExplainNasa, useNasaPictures } from "../../features/nasa/hooks";
import styles from "./NasaPage.module.css";

function PictureCard({ picture }: { picture: ApodPicture }) {
  const [expanded, setExpanded] = useState(false);
  const explain = useExplainNasa();
  const toast = useToast();

  const handleExplain = () => {
    explain.mutate(
      { date: picture.date },
      {
        onSuccess: () => {
          toast.add({
            title: "Explanation ready",
            description: "Translated to Hebrew by Gemini and cached.",
          });
        },
        onError: (err) => {
          toast.add({
            title: "Translation failed",
            description: err.message,
          });
        },
      },
    );
  };

  const isLong = picture.explanation.length > 220;
  const displayedExplanation =
    expanded || !isLong
      ? picture.explanation
      : `${picture.explanation.slice(0, 220)}...`;

  return (
    <Card className={styles.card}>
      <div className={styles.mediaWrapper}>
        {picture.media_type === "video" ? (
          <iframe
            src={picture.url}
            title={picture.title}
            className={styles.videoIframe}
            allowFullScreen
          />
        ) : (
          <img
            src={picture.url}
            alt={picture.title}
            loading="lazy"
            className={styles.image}
          />
        )}
      </div>

      <div className={styles.cardContent}>
        <div className={styles.cardMeta}>
          <time dateTime={picture.date}>{picture.date}</time>
          {picture.media_type === "video" && <span>Video</span>}
        </div>

        <h2 className={styles.cardTitle}>{picture.title}</h2>

        <p className={styles.explanationText}>
          {displayedExplanation}
          {isLong && (
            <button
              type="button"
              className={styles.moreButton}
              onClick={() => setExpanded(!expanded)}
            >
              {expanded ? " Show less" : " Read more"}
            </button>
          )}
        </p>

        {/* Hebrew Explanation (if available) */}
        {picture.translation ? (
          <div className={styles.translationBox}>
            <div className={styles.hebrewHeader}>
              <h3 className={styles.hebrewTitle}>
                {picture.translation.hebrew_title}
              </h3>
              <span className={styles.cachedBadge}>✓ מתורגם</span>
            </div>
            <p className={styles.hebrewSummary}>
              {picture.translation.hebrew_summary}
            </p>
            <div className={styles.tagsContainer}>
              {picture.translation.tags.map((tag) => (
                <span key={tag} className={styles.tagBadge}>
                  {tag}
                </span>
              ))}
            </div>
          </div>
        ) : (
          <div className={styles.explainAction}>
            {explain.isPending ? (
              <div className={styles.thinkingIndicator}>
                <Spinner />
                <span>ג&apos;מיני מסביר ומנתח...</span>
              </div>
            ) : (
              <Button
                variant="secondary"
                onClick={handleExplain}
                disabled={explain.isPending}
              >
                הסבר בעברית (Explain in Hebrew)
              </Button>
            )}
            {explain.isError && (
              <div className={styles.cardError}>
                {explain.error.message || "Failed to generate explanation."}
              </div>
            )}
          </div>
        )}
      </div>
    </Card>
  );
}

export default function NasaPage() {
  const {
    data: pictures,
    isLoading,
    isError,
    error,
    refetch,
    isFetching,
  } = useNasaPictures(9);

  return (
    <main className={styles.page}>
      <header className={styles.header}>
        <div className={styles.topBar}>
          <div>
            <h1 className={styles.title}>NASA Space Pictures</h1>
            <p className={styles.subtitle}>
              Astronomy Picture of the Day (APOD) archive powered by NASA, with
              simplified Hebrew explanations and tags generated by Gemini AI.
            </p>
          </div>
          <Button
            variant="secondary"
            onClick={() => void refetch()}
            disabled={isFetching}
          >
            {isFetching ? "Loading..." : "↻ Load More Pictures"}
          </Button>
        </div>
      </header>

      {isLoading ? (
        <div className={styles.stateContainer}>
          <Spinner />
          <p>Connecting to NASA deep space archive...</p>
        </div>
      ) : isError ? (
        <div className={styles.stateContainer}>
          <div className={styles.errorState}>
            <h2>Could not load pictures</h2>
            <p>{error?.message || "NASA API returned an error."}</p>
          </div>
          <Button onClick={() => void refetch()} variant="primary">
            Retry
          </Button>
        </div>
      ) : !pictures || pictures.length === 0 ? (
        <div className={styles.stateContainer}>
          <p>No pictures found. Try refreshing.</p>
        </div>
      ) : (
        <div className={styles.grid}>
          {pictures.map((pic) => (
            <PictureCard key={pic.date} picture={pic} />
          ))}
        </div>
      )}
    </main>
  );
}
